"""## FR-12 & FR-13: Ordered Amount Bands & NumPy Boolean Indexing (> INR 1,000)
* Segment transactions into 5 ordered monetary bands using `pd.cut()`.
* Isolate transactions above INR 1,000 using NumPy Boolean indexing.
"""

def segment_bands_and_threshold(df, amounts_np, threshold=1000.0):
    """FR-12 & FR-13: Segment amounts into 5 ordered bands and filter > threshold via NumPy."""
    # FR-12: Create 5 ordered transaction amount bands
    bins = [0, 250, 500, 1000, 2500, np.inf]
    labels = [
        "Very Low (<=250)",
        "Low (250-500)",
        "Medium (500-1,000)",
        "High (1,000-2,500)",
        "Very High (>2,500)"
    ]
    df["Amount_Band"] = pd.cut(df["Amount_INR"], bins=bins, labels=labels, right=True)

    band_summary = df.groupby("Amount_Band", observed=False).agg(
        Transaction_Count=("Transaction_ID", "count"),
        Total_Value_INR=("Amount_INR", "sum")
    )
    band_summary["Volume_Share_Pct"] = (band_summary["Transaction_Count"] / len(df)) * 100

    print("=== FR-12: Transaction Amount Bands ===")
    print(band_summary)

    # FR-13: NumPy Boolean indexing to isolate transactions above INR 1,000
    high_value_mask = amounts_np > threshold
    high_value_amounts = amounts_np[high_value_mask]

    count_above = len(high_value_amounts)
    pct_volume_above = (count_above / len(amounts_np)) * 100
    value_above = np.sum(high_value_amounts)
    pct_value_above = (value_above / np.sum(amounts_np)) * 100

    print(f"\n=== FR-13: NumPy Boolean Indexing (Amount_INR > INR {threshold:,.0f}) ===")
    print(f"Transactions Above Threshold: {count_above} ({pct_volume_above:.2f}% of volume)")
    print(f"Total Value Above Threshold:  INR {value_above:,.2f} ({pct_value_above:.2f}% of total value)")


segment_bands_and_threshold(df_clean, amounts_np, threshold=1000.0)

