import numpy as np
import pandas as pd

# Clean display formatting for Pandas tables
pd.set_option("display.float_format", "{:,.2f}".format)
pd.set_option("display.max_columns", 10)
pd.set_option("display.width", 120)


def load_and_inspect_data(filepath):
    """FR-01: Load CSV transaction records, parse dates, and inspect schema."""
    df = pd.read_csv(filepath)
    df["Transaction_Date"] = pd.to_datetime(df["Transaction_Date"])

    print("=== FR-01: Dataset Inspection ===")
    print(f"Dataset Shape: {df.shape[0]} rows x {df.shape[1]} columns")
    print(
        f"Date Range:    {df['Transaction_Date'].min().date()} to "
        f"{df['Transaction_Date'].max().date()} "
        f"({df['Transaction_Date'].nunique()} unique dates)"
    )
    print("\nColumn Data Types:")
    print(df.dtypes)
    print("\nMissing Values per Column:")
    print(df.isnull().sum())
    print("\nFirst 5 Rows:")
    print(df.head().to_string(index=False))
    return df


FILEPATH = "10_bank_transactions_1200.csv"
df_raw = load_and_inspect_data(FILEPATH)

"""## FR-02 & FR-03: Remove Missing-Amount Rows, Verify Unique IDs & Export Cleaned CSV
* Completely remove all rows with missing `Amount_INR` values using `.dropna(subset=["Amount_INR"])` instead of replacing them with estimated values.
* Verify 100% primary-key uniqueness of `Transaction_ID`.
* Export the cleaned dataset to `10_bank_transactions_1200_cleaned_removed.csv`.
"""

def clean_transaction_data(df_raw, output_csv="10_bank_transactions_1200_cleaned_removed.csv"):
    """FR-02 & FR-03: Remove rows with missing Amount_INR, verify unique IDs, and save cleaned CSV."""
    df = df_raw.copy()

    # FR-02: Detect and completely remove rows with missing Amount_INR
    rows_before = len(df)
    missing_before = int(df["Amount_INR"].isnull().sum())
    df = df.dropna(subset=["Amount_INR"]).reset_index(drop=True)
    rows_after = len(df)

    print("=== FR-02: Missing Value Removal ===")
    print(f"Rows before cleaning:               {rows_before}")
    print(f"Missing Amount_INR rows removed:    {missing_before} ({missing_before / rows_before * 100:.2f}%)")
    print(f"Rows remaining after cleaning:      {rows_after}")
    print(f"Missing Amount_INR after cleaning:  {int(df['Amount_INR'].isnull().sum())}")

    # FR-03: Check duplicate Transaction_ID values
    duplicate_id_count = int(df["Transaction_ID"].duplicated().sum())
    print("\n=== FR-03: Duplicate Transaction_ID Check ===")
    print(f"Duplicate Transaction_ID count:     {duplicate_id_count}")
    if duplicate_id_count > 0:
        df = df.drop_duplicates(subset=["Transaction_ID"], keep="first").reset_index(drop=True)
        print("Duplicate Transaction_ID records removed.")
    else:
        print("All Transaction_ID values are unique (100% primary-key uniqueness verified).")

    # Export cleaned CSV with uniform YYYY-MM-DD dates
    df_export = df.copy()
    df_export["Transaction_Date"] = df_export["Transaction_Date"].dt.strftime("%Y-%m-%d")
    df_export.to_csv(output_csv, index=False)
    print(f"\nCleaned dataset exported to: {output_csv} ({len(df_export)} rows x {df_export.shape[1]} columns)")

    return df


df_clean = clean_transaction_data(df_raw)

"""## FR-04 & FR-05: Credit vs. Debit Totals & Core NumPy Statistics
Calculate total Credits and Debits via Pandas on the 1,180 cleaned records, then compute mean, median, and standard deviation of `Amount_INR` using NumPy.
"""

def compute_core_statistics(df):
    """FR-04 & FR-05: Compute Credit/Debit totals (Pandas) and Amount_INR stats (NumPy)."""
    total_value = df["Amount_INR"].sum()

    # FR-04: Calculate total Credits and total Debits
    credit_debit = df.groupby("Transaction_Type")["Amount_INR"].agg(
        Transaction_Count="count",
        Total_Amount_INR="sum"
    )
    credit_debit["Value_Share_Pct"] = (credit_debit["Total_Amount_INR"] / total_value) * 100

    print("=== FR-04: Credit vs. Debit Totals ===")
    print(credit_debit)
    print(f"\nTotal Cleaned Transaction Value (N={len(df)}): INR {total_value:,.2f}")

    # FR-05: Calculate mean, median, and standard deviation using NumPy
    amounts_np = df["Amount_INR"].to_numpy()
    mean_amt = np.mean(amounts_np)
    median_amt = np.median(amounts_np)
    std_amt = np.std(amounts_np, ddof=1)

    print("\n=== FR-05: Transaction Amount Statistics (NumPy) ===")
    print(f"Mean:               INR {mean_amt:,.2f}")
    print(f"Median:             INR {median_amt:,.2f}")
    print(f"Standard Deviation: INR {std_amt:,.2f}")
    print(f"Min / Max:          INR {np.min(amounts_np):,.2f} / INR {np.max(amounts_np):,.2f}")

    return amounts_np


amounts_np = compute_core_statistics(df_clean)

"""## FR-06 & FR-07: Channel Volume & City Transaction Value Comparisons
Compare transaction counts across all 5 channels and total monetary value across all 5 cities.
"""

def compare_channels_and_cities(df):
    """FR-06 & FR-07: Compare transaction volume by Channel and total value by City."""
    total_value = df["Amount_INR"].sum()

    # FR-06: Compare transaction volume and share across channels
    channel_summary = (
        df.groupby("Channel")
        .agg(
            Transaction_Count=("Transaction_ID", "count"),
            Total_Value_INR=("Amount_INR", "sum")
        )
        .sort_values(by="Transaction_Count", ascending=False)
    )
    channel_summary["Volume_Share_Pct"] = (channel_summary["Transaction_Count"] / len(df)) * 100

    print("=== FR-06: Transaction Volume by Channel ===")
    print(channel_summary)

    # FR-07: Compare total transaction value and share across cities
    city_summary = (
        df.groupby("City")
        .agg(
            Total_Value_INR=("Amount_INR", "sum"),
            Transaction_Count=("Transaction_ID", "count")
        )
        .sort_values(by="Total_Value_INR", ascending=False)
    )
    city_summary["Value_Share_Pct"] = (city_summary["Total_Value_INR"] / total_value) * 100

    print("\n=== FR-07: Total Transaction Value by City ===")
    print(city_summary)


compare_channels_and_cities(df_clean)

"""## FR-08 & FR-09: Overall & Channel-Level Flagged Record Analysis
Calculate overall flagged count and percentage, then compare flagged percentages across all 5 channels using `pd.crosstab()`.
"""

def analyze_flagged_records(df):
    """FR-08 & FR-09: Calculate overall and channel-level flagged counts and percentages."""
    # FR-08: Overall flagged transaction count and percentage
    flagged_count = int((df["Flagged"] == "Yes").sum())
    flagged_pct = (flagged_count / len(df)) * 100

    print("=== FR-08: Overall Flagged Transaction Summary ===")
    print(f"Flagged Transactions: {flagged_count} out of {len(df)} ({flagged_pct:.2f}%)")
    print("Note: 'Flagged' is a supplied label in a synthetic dataset, not proof of fraud.")

    # FR-09: Compare flagged percentages across transaction channels
    flagged_by_channel = pd.crosstab(df["Channel"], df["Flagged"])
    flagged_by_channel["Total"] = flagged_by_channel.sum(axis=1)
    flagged_by_channel["Flagged_Pct"] = (flagged_by_channel["Yes"] / flagged_by_channel["Total"]) * 100
    flagged_by_channel = flagged_by_channel.sort_values(by="Flagged_Pct", ascending=False)

    print("\n=== FR-09: Flagged Percentage by Channel ===")
    print(flagged_by_channel)


analyze_flagged_records(df_clean)

